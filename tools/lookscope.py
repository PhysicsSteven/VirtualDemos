#!/usr/bin/env python3
"""Keep the demos warm under the Lab look: writes tools/paper-src/lookscope.css, which tools/genpaper.py appends to the
end of demos/lib/paper.css, then runs genpaper.py.

Steve 2026-11-08: the Lab look recolors the page around a demo only; the demos stay warm. Most demos read their drawing
colors from the tokens on <html> (getComputedStyle(document.documentElement)), so the Lab palette on :root turned their
canvases, 3D scenes and graphs teal and gray. On a demo page (one with .app) under Lab, the section
  1. puts the warm palette back on :root, so everything the demo draws is warm,
  2. puts the Lab palette (and the old token names mapped to it) on <body>, so the chrome around the demo is Lab,
  3. puts the warm palette back on .app .stage, so the picture and anything placed on it is warm.
Site pages, notes and worksheets keep the Lab palette on :root.

The values come from the palettes in tools/genpaper.py (LIGHT, DARK, LAB_LIGHT, LAB_DARK). After changing one, run
    python3 tools/lookscope.py            # rewrites lookscope.css and paper.css
    python3 tools/lookscope.py --check    # exits 1 when lookscope.css is stale (rules.cjs 'generated')
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genpaper  # noqa: E402

OUT = os.path.join(genpaper.SRC, "lookscope.css")


def build():
    R = ':root[data-vd-look="lab"]'
    D = ':not([data-theme="light"])'
    WL, WD = genpaper.block(genpaper.LIGHT, "light"), genpaper.block(genpaper.DARK, "dark")
    LL = genpaper.block({**genpaper.LIGHT, **genpaper.LAB_LIGHT}, "light")
    LD = genpaper.block({**genpaper.DARK, **genpaper.LAB_DARK}, "dark")
    ind = lambda b: "\n".join("  " + l for l in b.split("\n"))
    out = ["",
           "/* Generated by tools/lookscope.py from the palettes in tools/genpaper.py; do not edit by hand.",
           "   Under Lab, a demo page keeps the warm palette on :root and on its stage (the demos stay warm, Steve 2026-11-08)",
           "   and takes the Lab palette on <body> for the chrome around them. */"]
    for tail, light, dark in [("", WL, WD), (" body", LL, LD), (" .app .stage", WL, WD)]:
        out.append(f"{R}:has(.app){tail} {{\n{light}\n}}")
        out.append(f"@media (prefers-color-scheme: dark) {{\n  {R}{D}:has(.app){tail} {{\n{ind(dark)}\n  }}\n}}")
        out.append(f'{R}[data-theme="dark"]:has(.app){tail} {{\n{dark}\n}}')
    return "\n".join(out) + "\n"


def main(argv):
    new = build()
    cur = open(OUT).read() if os.path.exists(OUT) else None
    if "--check" in argv:
        ok = cur == new
        print("lookscope:", "up to date" if ok else "stale; run python3 tools/lookscope.py")
        return 0 if ok else 1
    if cur != new:
        open(OUT, "w").write(new)
    os.system(f'{sys.executable} "{os.path.join(os.path.dirname(os.path.abspath(__file__)), "genpaper.py")}"')
    print("lookscope: wrote tools/paper-src/lookscope.css")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
