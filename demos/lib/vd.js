  /* The Set up card: controls on the picture that are set before a run. VD.setupCard(card, { grip, within }) returns
     { away(on), ghost(on) }:
       away(true)   the card fades away and goes inert while the apparatus runs; away(false) brings it back (call it on Pause)
       ghost(true)  the card turns see through and lets the pointer pass while something under it is dragged
     Where the card floats over the picture (position absolute), its grip (default: its first child) drags it anywhere over
     the picture, the arrow keys on the grip move it 10 px (Shift: 40 px), and a double click puts it back. The move is a
     CSS translate on top of wherever the demo places the card, and it stays inside the picture: the card's offsetParent,
     or the element (or selector) given as within, for a card placed on the bench over a stage beside the sidebar. On phones, where the
     card sits under the picture, it does not move. */
  VD.setupCard = function (card, o) {
    o = o || {};
    var grip = typeof o.grip === 'string' ? card.querySelector(o.grip) : o.grip || card.firstElementChild, dx = 0, dy = 0;
    var box = function () { return (typeof o.within === 'string' ? document.querySelector(o.within) : o.within) || card.offsetParent || card.parentElement; };
    var floating = function () { return getComputedStyle(card).position === 'absolute'; };
    function place(x, y) {
      card.style.translate = '';
      var p = box().getBoundingClientRect(), r = card.getBoundingClientRect();
      x = Math.max(p.left - r.left, Math.min(p.right - r.right, x)); y = Math.max(p.top - r.top, Math.min(p.bottom - r.bottom, y));
      dx = Math.round(x); dy = Math.round(y); card.style.translate = dx || dy ? dx + 'px ' + dy + 'px' : '';
    }
    function mark() { card.classList.toggle('vd-movable', floating()); if (!floating() && (dx || dy)) { dx = dy = 0; card.style.translate = ''; } }
    if (grip) {
      grip.classList.add('vd-grip'); grip.setAttribute('tabindex', '0'); grip.setAttribute('role', 'button');
      grip.setAttribute('aria-label', (grip.textContent.trim() ? grip.textContent.trim() + '. ' : '') + 'Drag, or use the arrow keys, to move this card; double click to put it back');
      var sx = 0, sy = 0, ox = 0, oy = 0, on = false;
      grip.addEventListener('pointerdown', function (e) { if (!floating() || e.button) return; on = true; sx = e.clientX; sy = e.clientY; ox = dx; oy = dy; grip.setPointerCapture(e.pointerId); card.classList.add('vd-dragging'); e.preventDefault(); });
      grip.addEventListener('pointermove', function (e) { if (on) place(ox + e.clientX - sx, oy + e.clientY - sy); });
      var end = function () { on = false; card.classList.remove('vd-dragging'); };
      grip.addEventListener('pointerup', end); grip.addEventListener('pointercancel', end);
      grip.addEventListener('dblclick', function () { place(0, 0); });
      grip.addEventListener('keydown', function (e) {
        var k = { ArrowLeft: [-1, 0], ArrowRight: [1, 0], ArrowUp: [0, -1], ArrowDown: [0, 1] }[e.key]; if (!k || !floating()) return;
        var s = e.shiftKey ? 40 : 10; place(dx + k[0] * s, dy + k[1] * s); e.preventDefault(); e.stopPropagation(); });
      mark(); window.addEventListener('resize', function () { mark(); if (dx || dy) place(dx, dy); });
    }
    return {
      away: function (on) { card.classList.toggle('away', !!on); card.inert = !!on; },
      ghost: function (on) { card.classList.toggle('ghost', !!on); },
      reset: function () { place(0, 0); },
    };
  };

  /* VD.fitStage(stage): for a picture whose controls float over it on cards (position absolute, over a scene that fills
     the stage), a minimum height that fits every card with a control on it, and every handle placed on the drawing, so a
     short window or Projector never cuts a control off. It only grows the stage past what its CSS gives, and only while a card would be cut; it measures again
     when the window, Projector, the stage or a card changes size. A card's offset from the edge it is placed by (top or
     bottom) is kept, so a card placed from the bottom ends up as far from the bottom as before. Returns update(). */
  VD.fitStage = function (stage) {
    stage = typeof stage === 'string' ? document.querySelector(stage) : stage || document.getElementById('stage');
    if (!stage) return function () {};
    var queued = false, seen = new Set(), ro = window.ResizeObserver ? new ResizeObserver(function () { queue(); }) : null;
    function cards() {
      var out = new Set();
      stage.querySelectorAll('input:not([type=hidden]), button, select, textarea, [role=slider]').forEach(function (c) {
        if (!c.getClientRects().length) return;
        if (getComputedStyle(c).position === 'absolute') out.add(c);   /* a handle placed on the drawing */
        for (var a = c.parentElement; a && a !== stage; a = a.parentElement) if (getComputedStyle(a).position === 'absolute') { out.add(a); break; }
      });
      return out;
    }
    function update() {
      queued = false; stage.style.minHeight = '';
      var s = stage.getBoundingClientRect(), need = 0;
      cards().forEach(function (k) {
        if (ro && !seen.has(k)) { seen.add(k); ro.observe(k); }
        var cs = getComputedStyle(k); if (cs.visibility === 'hidden') return;
        var r = k.getBoundingClientRect(); if (r.top >= s.top - 1 && r.bottom <= s.bottom + 1) return;
        need = Math.max(need, r.height + Math.max(r.top - s.top, s.bottom - r.bottom, 0));
      });
      if (need > s.height + 1) stage.style.minHeight = Math.ceil(need) + 'px';
    }
    /* measured on the next frame, outside the ResizeObserver callback, so setting the height cannot start a loop */
    function queue() { if (!queued) { queued = true; requestAnimationFrame(update); } }
    if (ro) ro.observe(stage);
    window.addEventListener('resize', queue);
    new MutationObserver(queue).observe(document.documentElement, { attributes: true, attributeFilter: ['data-projector'] });
    stage.addEventListener('click', queue);
    queue();
    return update;
  };

  /* VD.typeIn(out, o): click or tap a readout (or focus it and press Enter, or just start typing) to type an exact value.
     o = { get, set, min, max, step, unit, label, can, knobs, seed }; min, max and step may be numbers or functions. The typed value is
     clamped to min..max and rounded to the step from min, then handed to set(v); a value that was out of range shows the range
     for a moment. Enter or tapping away keeps it, Esc cancels. The unit is o.unit, or the text after the number in the readout.
     Phones get the number keypad, with a ± key beside the field when the range goes below zero (the keypad has no minus). o.can() false (Blind, Mystery) leaves the
     readout alone. o.seed() gives the starting text when the readout's own number is not in o.unit (kHz shown, Hz typed). Each element in o.knobs opens the same entry on a double click, on Enter, or on a typed digit. */
  /* the entry itself, shared by VD.typeIn (in place of a readout) and VD.typeAt (floating over a picture). host = { text, put(ed),
     done(), rect(), back() }: the readout text the unit and starting value come from, where the entry goes, what to restore */
  function entry(o, host) {
    var f = function (x) { return typeof x === 'function' ? x() : x; };
    var lab = o.label || 'value', unit = '', ed = null, field = null;
    var num = function (s) { var m = String(s).replace(/[−–]/g, '-').replace(',', '.').match(/^\s*([+-]?(\d+\.?\d*|\.\d+)(e[+-]?\d+)?)(.*)$/i); return m ? { v: +m[1], rest: m[4].trim() } : null; };
    function note(text) {
      var n = document.createElement('div'), r = host.rect();
      n.className = 'vd-typein-note'; n.textContent = text; document.body.appendChild(n);
      n.style.left = Math.max(4, Math.min(innerWidth - n.offsetWidth - 4, r.left + r.width / 2 - n.offsetWidth / 2)) + 'px'; n.style.top = (r.bottom + 6) + 'px';
      setTimeout(function () { n.remove(); }, 2200);
    }
    function close(keep, back) {
      if (!ed) return true;
      if (keep) {
        var p = num(field.value);
        if (!p || p.rest !== '' && p.rest !== unit) { if (back) { field.classList.add('bad'); field.select(); return false; } keep = false; }
        else {
          var lo = +f(o.min), hi = +f(o.max), st = +f(o.step), v = p.v, r = Math.max(lo, Math.min(hi, v));
          if (st > 0) { r = lo + Math.round((r - lo) / st) * st; if (r > hi + 1e-9) r -= st; r = +r.toFixed(6); }
          var dp = st > 0 ? Math.max(0, Math.min(6, Math.ceil(-Math.log10(st) - 1e-9))) : null, fmt = function (x) { return (dp === null ? String(x) : x.toFixed(dp)).replace('-', '−') + (unit ? (/^(°|%)$/.test(unit) ? '' : ' ') + unit : ''); };
          var said = v < lo || v > hi ? 'Range ' + fmt(lo) + ' to ' + fmt(hi) : Math.abs(r - v) > 1e-9 ? 'Set to ' + fmt(r) + ', in steps of ' + fmt(st) : '';
        }
      }
      var e = ed; ed = null; e.remove(); host.done();
      if (keep) { o.set(r); if (said) note(said); }
      if (back) host.back();
      return true;
    }
    function open(seed) {
      if (ed || o.can && !o.can()) return false;
      var p = num(host.text()); if (p) unit = p.rest; if (o.unit != null) unit = o.unit;
      ed = document.createElement('span'); ed.className = 'vd-typein';
      field = document.createElement('input'); field.type = 'text'; field.autocomplete = 'off'; field.spellcheck = false;
      field.setAttribute('inputmode', 'decimal'); field.setAttribute('enterkeyhint', 'done');
      field.setAttribute('aria-label', 'Type ' + lab + (unit ? ', in ' + unit : '') + ', then press Enter');
      field.value = seed != null ? seed : o.seed ? o.seed() : p ? String(p.v) : String(+o.get());
      var fit = function () { field.style.width = Math.max(3, field.value.length + 0.5) + 'ch'; };
      fit(); field.addEventListener('input', fit);
      ed.appendChild(field);
      if (+f(o.min) < 0) {
        var pm = document.createElement('button'); pm.type = 'button'; pm.className = 'vd-pm'; pm.textContent = '±'; pm.tabIndex = -1; pm.setAttribute('aria-label', 'Change sign');
        pm.addEventListener('pointerdown', function (e) { e.preventDefault(); });
        pm.addEventListener('click', function () { var s = field.value.replace(/−/g, '-').trim(); field.value = s[0] === '-' ? s.slice(1) : '-' + s; field.focus(); });
        ed.insertBefore(pm, field);
      }
      if (unit) { var u = document.createElement('span'); u.className = 'vd-unit'; u.textContent = unit; ed.appendChild(u); }
      host.put(ed);
      field.addEventListener('keydown', function (e) {
        e.stopPropagation(); field.classList.remove('bad');
        if (e.key === 'Enter') { close(true, true); e.preventDefault(); } else if (e.key === 'Escape') { close(false, true); e.preventDefault(); }
      });
      field.addEventListener('blur', function () { close(true, false); });
      ['pointerdown', 'click', 'wheel'].forEach(function (t) { ed.addEventListener(t, function (e) { e.stopPropagation(); }); });
      field.focus(); if (seed == null) field.select();
      return true;
    }
    return { open: open, close: close };
  }
  /* VD.nice(x[, rel]): a slider that moves in fine or logarithmic steps sticks to round values. x is returned as the nearest
     number with two significant figures (0.75, 1.5, 300, 5.2) when it lies within rel (default 0.6 %) of it, and unchanged
     otherwise, so a hand can land on the value a worksheet names while every value in between stays reachable (2026-11-07). */
  VD.nice = function (x, rel) {
    if (!(x > 0) || !isFinite(x)) return x;
    var c = +x.toPrecision(2);
    return Math.abs(x / c - 1) <= (rel == null ? 0.006 : rel) ? c : x;
  };
