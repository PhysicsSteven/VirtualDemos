  /* Picture size (Steve, 2026-10-26, after Chladni on a Surface Pro drew its graph bigger than the plate). On a window at
     least 821 px wide (desktops, laptops, tablets), the picture is the stage's row with the most canvas and svg area. A
     short wide window used to squash it into a strip (the controls under it take the height), so it now keeps a height of
     at least a third of its width, up to 400 px and 60 % of the window's height (never less than its CSS gives); the page
     scrolls instead. Big screens are left as they were. A grip on the stage's bottom edge makes it taller or shorter: drag it (mouse or finger), or focus it
     and press the arrow keys (Shift for bigger steps); a double click or Home puts it back. The size is kept per demo on
     this device (localStorage vd-size:<demo>, a factor on the default height) and Reset all clears it. It grows the stage
     (the picture's row takes the extra), or, where that row does not stretch, gives the picture a minimum height; where
     neither works the grip is left off. It never shrinks a picture below what its CSS gives, so nothing is ever cut off.
     Every demo redraws on its own ResizeObserver. VD.pictureSize.factor(), .set(f) and .pic() are there for tests. */
  var SIZE_KEY = 'vd-size:' + (location.pathname.split('/').pop().replace(/\.html$/, '') || 'index');
  VD.pictureSize = function (stage) {
    stage = stage || document.querySelector('.bench > .stage'); if (!stage) return null;
    var bench = stage.parentElement, f = 1, mode = '', pic = null, h0 = 0, def = 0, cur = 0, queued = false;
    try { var sv = parseFloat(localStorage.getItem(SIZE_KEY)); if (sv > 0 && sv < 10) f = sv; } catch (_) {}
    var grip = document.createElement('div');
    grip.className = 'vd-size'; grip.tabIndex = 0; grip.setAttribute('role', 'slider'); grip.setAttribute('aria-orientation', 'vertical');
    grip.setAttribute('aria-label', 'Picture height'); grip.title = 'Drag to make the picture taller or shorter (double click puts it back)';
    grip.setAttribute('data-vd-noshare', ''); grip.hidden = true;
    if (getComputedStyle(bench).position === 'static') bench.style.position = 'relative';
    bench.appendChild(grip);
    function findPic() {   /* the stage's row with the most drawing area in it */
      var area = new Map(), best = null, ba = 0;
      stage.querySelectorAll('canvas, svg').forEach(function (c) {
        if (c.closest('.vd-size, button, [hidden]')) return;
        var r = c.getBoundingClientRect(), row = c; if (!r.width || !r.height) return;
        while (row.parentElement !== stage) row = row.parentElement;
        if (/^(CANVAS|svg)$/i.test(row.tagName)) row = stage;   /* a drawing that fills the stage: the stage is the picture */
        area.set(row, (area.get(row) || 0) + r.width * r.height);
      });
      area.forEach(function (a, row) { if (a > ba) { ba = a; best = row; } });
      return ba < 40000 ? null : best;
    }
    function clear() { stage.style.height = ''; if (pic && pic !== stage) pic.style.minHeight = ''; mode = ''; }
    function ht() { return pic.getBoundingClientRect().height; }
    function apply(T) {
      clear(); var h = ht(); cur = h; if (T <= h + 1) return true;
      var s0 = stage.getBoundingClientRect().height; stage.style.height = (s0 + T - h) + 'px';
      var g = (ht() - h) / (T - h);   /* the share of the extra height the picture's row takes (below 1 when rows split it) */
      if (g > 0.2 && g < 0.99) stage.style.height = (s0 + (T - h) / g) + 'px';
      if (ht() >= T - 1) { mode = 'stage'; cur = ht(); return true; }
      stage.style.height = ''; if (pic === stage) { cur = ht(); return false; }
      pic.style.minHeight = T + 'px';
      if (ht() >= T - 1 && stage.getBoundingClientRect().bottom >= pic.getBoundingClientRect().bottom - 1) { mode = 'pic'; cur = ht(); return true; }
      clear(); cur = ht(); return false;
    }
    function place() {
      if (grip.hidden) return;
      grip.style.left = (stage.offsetLeft + stage.offsetWidth / 2 - grip.offsetWidth / 2) + 'px';
      grip.style.top = (stage.offsetTop + stage.offsetHeight - grip.offsetHeight / 2) + 'px';
    }
    function lo() { return h0 / def; }
    function hi() { return Math.max(1, window.innerHeight * 1.5 / def); }
    function aria() { grip.setAttribute('aria-valuenow', String(Math.round(cur))); grip.setAttribute('aria-valuetext', Math.round(cur) + ' px tall');
      grip.setAttribute('aria-valuemin', String(Math.round(h0))); grip.setAttribute('aria-valuemax', String(Math.round(def * hi()))); }
    function update() {
      queued = false;
      if (window.innerWidth < 821) { if (pic) clear(); pic = null; grip.hidden = true; return; }
      if (pic) clear();
      pic = findPic(); if (!pic) { grip.hidden = true; return; }
      var r = pic.getBoundingClientRect(); h0 = r.height;
      def = Math.max(h0, Math.min(r.width / 3, window.innerHeight * 0.6, 400));
      f = Math.min(hi(), Math.max(lo(), f));
      grip.hidden = !apply(h0 + 40);   /* a picture that cannot grow gets no grip, and keeps its CSS height */
      apply(grip.hidden ? h0 : def * f);
      aria(); place();
    }
    function queue() { if (!queued) { queued = true; requestAnimationFrame(update); } }
    function save() { try { if (Math.abs(f - 1) < 0.01) localStorage.removeItem(SIZE_KEY); else localStorage.setItem(SIZE_KEY, String(Math.round(f * 1000) / 1000)); } catch (_) {} }
    function setF(v, keep) { f = Math.min(hi(), Math.max(lo(), v)); apply(def * f); aria(); place(); if (keep !== false) save(); }
    var drag = null;
    grip.addEventListener('pointerdown', function (e) {
      if (e.button) return; e.preventDefault(); grip.setPointerCapture(e.pointerId); grip.classList.add('on');
      drag = { y: e.clientY, h: cur, raf: 0 };
    });
    grip.addEventListener('pointermove', function (e) {
      if (!drag) return; var y = e.clientY;
      if (!drag.raf) drag.raf = requestAnimationFrame(function () { if (!drag) return; drag.raf = 0; setF((drag.h + y - drag.y) / def, false); });
    });
    function end() { if (!drag) return; drag = null; grip.classList.remove('on'); save(); }
    grip.addEventListener('pointerup', end); grip.addEventListener('pointercancel', end);
    grip.addEventListener('dblclick', function () { setF(1); });
    grip.addEventListener('keydown', function (e) {
      var step = (e.shiftKey ? 120 : 30) / def, k = e.key;
      if (k === 'ArrowDown' || k === 'ArrowRight') setF(cur / def + step);
      else if (k === 'ArrowUp' || k === 'ArrowLeft') setF(cur / def - step);
      else if (k === 'Home') setF(1);
      else return;
      e.preventDefault();
    });
    window.addEventListener('resize', queue);
    new MutationObserver(queue).observe(document.documentElement, { attributes: true, attributeFilter: ['data-projector'] });
    stage.addEventListener('click', function () { setTimeout(queue, 0); });   /* a view switch can change which canvas is the picture */
    if (window.ResizeObserver) new ResizeObserver(place).observe(stage);
    if (document.fonts && document.fonts.ready) document.fonts.ready.then(queue);
    if (document.readyState === 'complete') queue(); else window.addEventListener('load', function () { queue(); });
    VD.pictureSize.factor = function () { return f; };
    VD.pictureSize.set = function (v) { setF(v); };
    VD.pictureSize.pic = function () { return pic; };
    VD.pictureSize.natural = function () { return h0; };
    VD.pictureSize.grip = grip;
    return update;
  };

  /* Pieces of a picture that can be resized (Steve, 2026-10-28: the free body diagram in Forces took more room than the
     scene). VD.split(el, o) puts a divider on the line between two pieces that a demo draws side by side or one above the
     other in el (a canvas, or the box that holds the pieces). Drag it (mouse or finger) and it snaps to a third, a half, two
     thirds and the demo's own default when let go near one; the snap marks show while dragging. Focus it and the arrow keys
     step from snap to snap (Shift: 1 % steps); Home or a double click puts the default back. The choice is kept per demo and
     direction on this device (localStorage vd-split:<demo>:<key>:<x|y>) and Reset all clears it.
     o = { key, axis, def, min, max, snaps, onChange, label, host, box }:
       axis()    'x' (pieces side by side, divider upright), 'y' (one above the other) or null (no divider in this layout)
       def       the default share of the first piece (left or top), a number or a function of the axis
       min, max  limits on that share (default 0.25 and 0.75); snaps outside them are left out
       onChange(f) runs when the share changes: the demo redraws with s.f()
       host      the element the divider is placed in (default el's parent; it must be positioned)
       box()     the client rectangle the share is taken of, where it is not el's own box (two rows of panes in a grid)
     Returns s: s.f() the share now (for the current axis), s.place() after the demo lays out (puts the divider on the line),
     s.set(f) for tests. The demo reads s.f() wherever it used a fixed share, so nothing else changes. */
  var SPLIT_PRE = 'vd-split:' + (location.pathname.split('/').pop().replace(/\.html$/, '') || 'index') + ':';
  VD.split = function (el, o) {
    o = o || {}; var host = o.host || el.parentElement, key = SPLIT_PRE + (o.key || 'main') + ':', ax = null, frac = {};
    var lim = function (v) { return Math.min(o.max == null ? 0.75 : o.max, Math.max(o.min == null ? 0.25 : o.min, v)); };
    var def = function (a) { return lim(typeof o.def === 'function' ? o.def(a) : o.def == null ? 0.5 : o.def); };
    function load(a) { if (frac[a] != null) return frac[a]; var v = NaN; try { v = parseFloat(localStorage.getItem(key + a)); } catch (_) {} return v > 0 && v < 1 ? (frac[a] = lim(v)) : def(a); }   /* the default is read live (it may follow the window) until a choice is made */
    function snaps(a) { var out = [def(a)]; (o.snaps || [1 / 3, 1 / 2, 2 / 3]).forEach(function (v) { if (v === lim(v) && out.every(function (u) { return Math.abs(u - v) > 0.01; })) out.push(v); }); return out.sort(function (p, q) { return p - q; }); }
    var bar = document.createElement('div'); bar.className = 'vd-split'; bar.tabIndex = 0; bar.hidden = true;
    bar.setAttribute('role', 'separator'); bar.setAttribute('aria-label', o.label || 'Divider between the two pieces of the picture');
    bar.title = 'Drag to resize (double click puts it back)'; bar.setAttribute('data-vd-noshare', '');
    var marks = document.createElement('div'); marks.className = 'vd-split-marks'; marks.hidden = true;
    if (getComputedStyle(host).position === 'static') host.style.position = 'relative';
    host.appendChild(marks); host.appendChild(bar);
    function rect() { return o.box ? o.box() : el.getBoundingClientRect(); }
    function box() { var r = rect(), h = host.getBoundingClientRect();
      return { x: r.left - h.left + host.scrollLeft - host.clientLeft, y: r.top - h.top + host.scrollTop - host.clientTop, w: r.width, h: r.height }; }
    function place() {
      ax = o.axis ? o.axis() : 'x'; bar.hidden = !ax; if (!ax) return;
      var b = box(), f = load(ax); bar.classList.toggle('vd-split-y', ax === 'y');
      if (ax === 'x') Object.assign(bar.style, { left: (b.x + b.w * f) + 'px', top: b.y + 'px', width: '', height: b.h + 'px' });
      else Object.assign(bar.style, { left: b.x + 'px', top: (b.y + b.h * f) + 'px', width: b.w + 'px', height: '' });
      bar.setAttribute('aria-orientation', ax === 'x' ? 'vertical' : 'horizontal');
      bar.setAttribute('aria-valuenow', String(Math.round(f * 100))); bar.setAttribute('aria-valuetext', Math.round(f * 100) + ' % for the first piece');
    }
    function showMarks(on) {
      marks.hidden = !on; if (!on) return; var b = box(); marks.innerHTML = '';
      snaps(ax).forEach(function (v) { var m = document.createElement('i'); m.className = ax === 'y' ? 'y' : 'x';
        if (ax === 'x') Object.assign(m.style, { left: (b.x + b.w * v) + 'px', top: b.y + 'px', height: b.h + 'px' });
        else Object.assign(m.style, { left: b.x + 'px', top: (b.y + b.h * v) + 'px', width: b.w + 'px' });
        marks.appendChild(m); });
    }
    function save() { try { if (Math.abs(frac[ax] - def(ax)) < 0.001) localStorage.removeItem(key + ax); else localStorage.setItem(key + ax, String(Math.round(frac[ax] * 1000) / 1000)); } catch (_) {} }
    function set(v, keep) { if (!ax) return; v = lim(v); if (Math.abs(v - load(ax)) < 0.0005) return; frac[ax] = v; place(); if (o.onChange) o.onChange(v); if (keep !== false) save(); }
    function nearest(v) { var best = v, d = 0.035; snaps(ax).forEach(function (u) { if (Math.abs(u - v) < d) { d = Math.abs(u - v); best = u; } }); return best; }
    var drag = null;
    bar.addEventListener('pointerdown', function (e) { if (e.button || !ax) return; e.preventDefault(); bar.setPointerCapture(e.pointerId); bar.classList.add('on'); drag = { raf: 0 }; showMarks(true); });
    bar.addEventListener('pointermove', function (e) {
      if (!drag) return; var cx = e.clientX, cy = e.clientY;
      if (!drag.raf) drag.raf = requestAnimationFrame(function () { if (!drag) return; drag.raf = 0; var r = rect();
        var v = ax === 'x' ? (cx - r.left) / r.width : (cy - r.top) / r.height, n = nearest(v); set(Math.abs(n - v) < 0.012 ? n : v, false); });
    });
    function end() { if (!drag) return; drag = null; bar.classList.remove('on'); showMarks(false); set(nearest(load(ax)), false); save(); }
    bar.addEventListener('pointerup', end); bar.addEventListener('pointercancel', end);
    bar.addEventListener('dblclick', function () { set(def(ax)); frac[ax] = null; });
    bar.addEventListener('keydown', function (e) {
      var k = e.key, f = load(ax), up = k === 'ArrowRight' || k === 'ArrowDown', dn = k === 'ArrowLeft' || k === 'ArrowUp';
      if (k === 'Home') { set(def(ax)); frac[ax] = null; }
      else if ((up || dn) && e.shiftKey) set(f + (up ? 0.01 : -0.01));
      else if (up) { var nx = snaps(ax).filter(function (u) { return u > f + 0.002; })[0]; set(nx == null ? lim(1) : nx); }
      else if (dn) { var pv = snaps(ax).filter(function (u) { return u < f - 0.002; }).pop(); set(pv == null ? lim(0) : pv); }
      else return;
      e.preventDefault();
    });
    if (window.ResizeObserver) new ResizeObserver(function () { place(); }).observe(el);
    window.addEventListener('resize', place);
    (el.closest('.stage') || host).addEventListener('click', function () { setTimeout(place, 0); });   /* a mode or view switch can move or hide the line */
    var s = { f: function () { var a = o.axis ? o.axis() : 'x'; return a ? load(a) : def(a); }, place: place, set: function (v) { set(v); }, el: bar };   /* the direction is read live, so a draw right after a resize gets the right share */
    requestAnimationFrame(place); return s;   /* placed once the demo has set itself up */
  };

  /* VD.splitPanes(a, b, o): VD.split for two panes that are separate elements side by side or one above the other in the
     same grid (or flex) box, such as a scene pane and a plot pane. Nothing to change in the demo's drawing: the divider sets
     the two grid tracks (or flex shares) and each pane's own ResizeObserver redraws it. The default is the panes' share as
     the page's CSS gives it, so the page opens as before. o = { key, label, min, max, snaps, when, onChange }: when() false
     leaves the panes as the CSS has them (no divider), e.g. on phones; onChange(f) for a demo that also needs to redraw.
     Returns the VD.split object. */
  VD.splitPanes = function (a, b, o) {
    o = o || {}; var c = a.parentElement, ax = 'y', nat = 0.5, on = false, s = null;
    var wide = function () { return o.when ? o.when() : window.innerWidth > 820; };
    function px(v) { return parseFloat(v) || 0; }
    var mine = {};   /* only what this divider set is cleared, never a template the demo set itself */
    function clear() { ['gridTemplateRows', 'gridTemplateColumns'].forEach(function (k) { if (mine[k] && c.style[k] === mine[k]) c.style[k] = ''; mine[k] = ''; });
      if (mine.flex) { a.style.flex = ''; b.style.flex = ''; mine.flex = false; }
      a.removeAttribute('data-vd-free'); b.removeAttribute('data-vd-free'); }
    function measure() {
      clear(); var ra = a.getBoundingClientRect(), rb = b.getBoundingClientRect();
      ax = rb.left >= ra.right - 2 ? 'x' : 'y';
      var sa = ax === 'x' ? ra.width : ra.height, sb = ax === 'x' ? rb.width : rb.height;
      on = wide() && sa > 0 && sb > 0 && !a.hidden && !b.hidden; nat = on ? sa / (sa + sb) : 0.5;
      return { ra: ra, rb: rb, sa: sa, sb: sb };
    }
    function apply(f) {
      var m = measure(); if (!on || Math.abs(f - nat) < 0.002) { if (o.onChange) o.onChange(f); return; }
      var cs = getComputedStyle(c);
      if (/grid/.test(cs.display)) {
        var prop = ax === 'x' ? 'gridTemplateColumns' : 'gridTemplateRows', list = cs[prop].split(/\s+/).map(px), gap = px(ax === 'x' ? cs.columnGap : cs.rowGap);
        var cr = c.getBoundingClientRect(), start = ax === 'x' ? m.ra.left - cr.left - c.clientLeft - px(cs.paddingLeft) : m.ra.top - cr.top - c.clientTop - px(cs.paddingTop);
        var i = -1, pos = 0; for (var k = 0; k < list.length; k++) { if (Math.abs(pos - start) < 2) { i = k; break; } pos += list[k] + gap; }
        if (i < 0 || i + 1 >= list.length) return;
        var tot = list[i] + list[i + 1]; list[i] = tot * f; list[i + 1] = tot * (1 - f);
        c.style[prop] = list.map(function (v) { return v.toFixed(2) + 'px'; }).join(' '); mine[prop] = c.style[prop];
      } else {   /* a px basis, so a box whose size follows its content keeps the panes' total; any spare room is shared in the same ratio */
        var tot = m.sa + m.sb; a.style.flex = f + ' ' + f + ' ' + (tot * f).toFixed(2) + 'px'; b.style.flex = (1 - f) + ' ' + (1 - f) + ' ' + (tot * (1 - f)).toFixed(2) + 'px'; mine.flex = true;
        a.setAttribute('data-vd-free', ax); b.setAttribute('data-vd-free', ax);   /* vd.css lifts a CSS floor on the panes (min-height: 400px) so the divider can move; a floor set inline (the picture size grip) stays */ }
      if (o.onChange) o.onChange(f);
    }
    var box = function () { var ra = a.getBoundingClientRect(), rb = b.getBoundingClientRect(), l = Math.min(ra.left, rb.left), t = Math.min(ra.top, rb.top), r = Math.max(ra.right, rb.right), btm = Math.max(ra.bottom, rb.bottom);
      return { left: l, top: t, right: r, bottom: btm, width: r - l, height: btm - t }; };
    measure();
    s = VD.split(c, { key: o.key || 'panes', host: c, box: box, axis: function () { return on ? ax : null; }, def: function () { return nat; },
      min: o.min, max: o.max, snaps: o.snaps, label: o.label || 'Divider between the two panes', onChange: function (f) { apply(f); s.place(); } });
    function again() { measure(); apply(s.f()); s.place(); }   /* measured first, so a default follows the panes as the CSS has them now */
    window.addEventListener('resize', again);
    new MutationObserver(again).observe(document.documentElement, { attributes: true, attributeFilter: ['data-projector'] });
    (a.closest('.stage') || c).addEventListener('click', function () { setTimeout(again, 0); });   /* a view switch can show, hide or move a pane */
    var queued = false; function queue() { if (!queued) { queued = true; requestAnimationFrame(function () { queued = false; again(); }); } }
    new MutationObserver(queue).observe(a, { attributes: true, attributeFilter: ['hidden', 'class'] });   /* a pane shown later (a 3D view once it loads) */
    new MutationObserver(queue).observe(b, { attributes: true, attributeFilter: ['hidden', 'class'] });
    again();
    return s;
  };

